"""
aggregate_results.py -- build Table 2 from the individual run records.

Reads every results/*/experiment.json and reports mean +/- standard
deviation of test F1 across seeds, as the paper does. Systems with no
completed runs are omitted rather than shown blank, so the table never
implies a number that was not computed.
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ["xlmr", "lapt", "random_lapt", "focus_lapt", "lgse_lapt"]
LABELS = {
    "xlmr": "XLM-R",
    "lapt": "+LAPT",
    "random_lapt": "+Random+LAPT",
    "focus_lapt": "+FOCUS+LAPT",
    "lgse_lapt": "+LGSE+LAPT",
}


def main():
    p = argparse.ArgumentParser(description="Aggregate Table 2 results")
    p.add_argument("--results-dir", type=Path, default=ROOT / "results")
    p.add_argument("--task", default=None)
    p.add_argument("--language", default=None)
    p.add_argument("-o", "--out", type=Path, default=None)
    args = p.parse_args()

    import sys
    sys.path.insert(0, str(ROOT / "src"))
    from evaluation.metrics import aggregate

    runs = defaultdict(list)
    for record_path in sorted(args.results_dir.glob("*/experiment.json")):
        r = json.load(open(record_path, encoding="utf-8"))
        if args.task and r["task"] != args.task:
            continue
        if args.language and r["language"] != args.language:
            continue
        runs[(r["language"], r["task"], r["system"])].append(r)

    if not runs:
        print("no completed runs matched -- run scripts/run_table2.sh first")
        return

    # Any hyperparameter the paper places in Table 1 but that could not be
    # recovered is marked `source: unavailable` in configs/base.yaml. If any
    # remain, the table says so: these numbers are then a reproduction under
    # documented substitutions, not a replication of the paper's.
    config_text = (ROOT / "configs" / "base.yaml").read_text(encoding="utf-8")
    n_unavailable = config_text.count("source: unavailable")

    lines = ["# Table 2", "",
             "Mean +/- standard deviation of test F1 across seeds.",
             "Generated by scripts/aggregate_results.py from results/;",
             "every figure comes from a completed run in this repository.", ""]
    if n_unavailable:
        lines += [
            f"> **Not a replication.** {n_unavailable} hyperparameters are "
            "marked `source: unavailable` in `configs/base.yaml`: the paper "
            "places them in Table 1, which could not be recovered. The values "
            "used are conventional defaults, not the paper's, so these "
            "figures are not directly comparable with the published Table 2.",
            "",
        ]

    for (language, task) in sorted({(l, t) for l, t, _ in runs}):
        lines += [f"## {language.title()} -- {task.upper()}", "",
                  "| System | F1 | seeds |", "|---|---|---|"]
        for system in ORDER:
            key = (language, task, system)
            if key not in runs:
                continue
            stats = aggregate([r["test"] for r in runs[key]])["f1"]
            seeds = sorted(r["seed"] for r in runs[key])
            lines.append(f"| {LABELS[system]} | {stats['mean']:.2f} "
                         f"± {stats['std']:.2f} | {len(seeds)} |")
        lines.append("")

    body = "\n".join(lines)
    print(body)
    out = args.out or args.results_dir / "TABLE2.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(f"written to {out}")


if __name__ == "__main__":
    main()
