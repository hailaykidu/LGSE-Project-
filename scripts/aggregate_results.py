"""
aggregate_results.py -- build Table 2 from the individual run records.

Reads every results/*/experiment.json and reports mean +/- standard
deviation of test F1 across seeds, as the paper does. Systems with no
completed runs are omitted rather than shown blank, so the table never
implies a number that was not computed.
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ["xlmr", "lapt", "random_lapt", "focus_lapt", "lgse_lapt"]
LABELS = {
    "xlmr": "XLM-R",
    "lapt": "+LAPT",
    "random_lapt": "+Random+LAPT",
    "focus_lapt": "+FOCUS+LAPT",
    "lgse_lapt": "+LGSE+LAPT",
}


def main():
    p = argparse.ArgumentParser(description="Aggregate Table 2 results")
    p.add_argument("--results-dir", type=Path, default=ROOT / "results")
    p.add_argument("--task", default=None)
    p.add_argument("--language", default=None)
    p.add_argument("-o", "--out", type=Path, default=None)
    args = p.parse_args()

    import sys
    sys.path.insert(0, str(ROOT / "src"))
    from evaluation.metrics import aggregate

    runs = defaultdict(list)
    for record_path in sorted(args.results_dir.glob("*/experiment.json")):
        r = json.load(open(record_path, encoding="utf-8"))
        if args.task and r["task"] != args.task:
            continue
        if args.language and r["language"] != args.language:
            continue
        runs[(r["language"], r["task"], r["system"])].append(r)

    if not runs:
        print("no completed runs matched -- run scripts/run_table2.sh first")
        return

    # Any hyperparameter the paper places in Table 1 but that could not be
    # recovered is marked `source: unavailable` in configs/base.yaml. If any
    # remain, the table says so: these numbers are then a reproduction under
    # documented substitutions, not a replication of the paper's.
    config_text = (ROOT / "configs" / "base.yaml").read_text(encoding="utf-8")
    n_unavailable = config_text.count("source: unavailable")

    lines = ["# Table 2", "",
             "Mean +/- standard deviation of test F1 across seeds.",
             "Generated by scripts/aggregate_results.py from results/;",
             "every figure comes from a completed run in this repository.", ""]
    if n_unavailable:
        lines += [
            f"> **Not a replication.** {n_unavailable} hyperparameter(s) are "
            "marked `source: unavailable` in `configs/base.yaml`: the paper "
            "introduces them but never states their values. The values used "
            "are the experimenter's, not the paper's, so these figures are "
            "not directly comparable with the published Table 2.",
            "",
        ]

    # W cannot be derived from the paper. A run that used one the authors
    # did not provide is not faithful to the published method, and the
    # generated table must say so rather than leaving it to DEVIATIONS.md.
    unfaithful = sorted({
        r.get("system", "?") for records in runs.values() for r in records
        if isinstance(r.get("projection"), dict)
        and not r["projection"].get("author_supplied", False)
    })
    if unfaithful:
        lines += [
            "> **Not faithful to the published method.** These runs used no "
            f"author-provided alignment matrix W: {', '.join(unfaithful)}. "
            "The paper introduces W (Sec 4.1) but never states how it is "
            "obtained, so any W used here is a substitution. See "
            "`DEVIATIONS.md` section 1a.",
            "",
        ]

    # Fidelity is rendered per row, not only in the notice above. A reader
    # scanning the table sees which systems required an author-supplied W
    # and whether they got one, without cross-referencing anything.
    def fidelity(records):
        projections = [r["projection"] for r in records
                       if isinstance(r.get("projection"), dict)]
        if not projections:
            # No projection at all: the baselines. Nothing to be unfaithful
            # about -- W is not part of these systems.
            return "n/a -- no alignment matrix required"
        if all(p.get("author_supplied") for p in projections):
            return "author-supplied W"
        if any(p.get("author_supplied") for p in projections):
            return "**MIXED -- some runs had no author-supplied W**"
        return "**not faithful -- no author-supplied W**"

    for (language, task) in sorted({(l, t) for l, t, _ in runs}):
        lines += [f"## {language.title()} -- {task.upper()}", "",
                  "| System | F1 | seeds | Alignment matrix W |",
                  "|---|---|---|---|"]
        for system in ORDER:
            key = (language, task, system)
            if key not in runs:
                continue
            stats = aggregate([r["test"] for r in runs[key]])["f1"]
            seeds = sorted(r["seed"] for r in runs[key])
            lines.append(f"| {LABELS[system]} | {stats['mean']:.2f} "
                         f"± {stats['std']:.2f} | {len(seeds)} | "
                         f"{fidelity(runs[key])} |")
        lines.append("")

    # Provenance for the runs behind the table. A figure is only defensible
    # if the code, configuration, data, seeds and environment that produced
    # it can all be named, so all five are rendered rather than left in the
    # JSON where a reader of the table would not see them.
    records = [r for rs in runs.values() for r in rs if "provenance" in r]
    if records:
        commits = sorted({r["provenance"]["commit"][:12] for r in records})
        configs = sorted({c for r in records
                          if (c := (r["provenance"].get("config_sha256") or "")[:12])})
        dirty = any(r["provenance"].get("dirty") for r in records)
        seeds = sorted({r["seed"] for r in records})
        unavailable = max(r.get("unavailable_hyperparameters", 0) for r in records)

        lines += ["## Provenance", "",
                  "| Field | Value |", "|---|---|",
                  f"| Commit | `{', '.join(commits)}` |",
                  f"| Config sha256 | `{', '.join(configs) or 'unavailable'}` |",
                  f"| Seeds | {', '.join(map(str, seeds))} ({len(seeds)} runs per system) |"]

        env = records[0]["provenance"]
        packages = env.get("packages", {})
        lines.append(f"| Environment | python {env.get('python', '?')}, "
                     + ", ".join(f"{k} {v}" for k, v in packages.items()) + " |")

        for lang, rec in (env.get("fasttext") or {}).items():
            lines.append(f"| FastText ({lang}) | dim {rec.get('dimension')}, "
                         f"vocab {rec.get('vocab_size'):,}, "
                         f"sha256 `{(rec.get('sha256') or '')[:12]}` |")

        # Group by language/task and prefer a record that carries a
        # manifest: a pair is only undocumented if *no* run of it had one.
        # An absent manifest is rendered as a gap, never omitted -- a missing
        # row would let a hand-assembled data directory look documented.
        by_pair = defaultdict(list)
        for r in records:
            by_pair[(r["language"], r["task"])].append(r)

        undocumented = []
        for key in sorted(by_pair):
            language, task = key
            group = by_pair[key]
            documented = [
                r for r in group
                if (m := r["provenance"].get("dataset_manifest"))
                and m.get("status") != "unavailable"
            ]
            label = f"Dataset ({language} {task.upper()})"

            if not documented:
                undocumented.append(key)
                lines.append(f"| {label} | **manifest unavailable -- "
                             f"splits not traceable** |")
                continue

            manifest = documented[0]["provenance"]["dataset_manifest"]
            detail = manifest.get("source", "unavailable")
            if manifest.get("split"):
                detail += f" -- {manifest['split']}"
            if "seed" in manifest:
                detail += f" (split seed {manifest['seed']})"
            if len(documented) < len(group):
                detail += (f" -- **{len(group) - len(documented)} of "
                           f"{len(group)} runs had no manifest**")
            lines.append(f"| {label} | {detail} |")

        lines.append(f"| Unavailable hyperparameters | {unavailable} |")
        lines.append("")

        if len(commits) > 1:
            lines += ["> **Runs span more than one commit.** The table mixes "
                      "results produced by different code.", ""]
        if dirty:
            lines += ["> **Some runs were made with uncommitted changes.** The "
                      "commit hash alone does not identify the code used.", ""]
        if undocumented:
            pairs = ", ".join(f"{l} {t.upper()}" for l, t in sorted(undocumented))
            lines += [f"> **Dataset manifest unavailable for: {pairs}.** Those "
                      "splits cannot be traced to a source, checksum or split "
                      "seed. Prepare data with `data/scripts/prepare_ner.py` "
                      "or `prepare_qa.py`, or rerun with `--require-manifest` "
                      "to refuse untraceable data outright.", ""]

    body = "\n".join(lines)
    print(body)
    out = args.out or args.results_dir / "TABLE2.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(f"written to {out}")


if __name__ == "__main__":
    main()
